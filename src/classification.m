// Nontrivial minimal complementary triples of one order.
//
// Gamma_T = <Gamma_emptyset, alpha_p : p in T> inside N(O)/K^*. For each T, find
// the ideals C, minimal under divisibility, at which the reduction map pi_C is
// injective on Gamma_T, and the conjugacy classes of complements H of
// pi_C(Gamma_T) in G_C.
// Public: LocalizedGroups, ReductionData, ReductionImage,
// MinimalComplementaryIdeals, ClassifyOrder, ClassificationExclusionReason,
// IsNontrivialMinimalIdeal.


LocalizedGroupFormat := recformat<
    order_data,
    admissible_ramified_primes,
    ramified_subset,             // T, sorted by norm
    subgroup,                    // Gamma_T inside order_data`normalizer_group
    subgroup_order,
    generator_elements           // generators of Gamma_T, as primitive quaternions
>;

// The reduction Gamma_T -> G_{p^k}, or -> W_{p^k} when uses_extension.
LocalImageFormat := recformat<
    quotient,
    uses_extension,
    ambient_group,
    image_subgroup,
    generator_images
>;

ReductionFormat := recformat<
    localized_unit_group,
    modulus_ideal,
    factors,                     // LocalImageFormat, one per prime power of C
    embeddings,                  // the group of each factor -> ambient_group
    ambient_group,               // G_C, the direct product of the factors
    image_subgroup,
    injective,
    complement_classes,          // one subgroup per conjugacy class
    normal_complement_classes
>;

PosetFormat := recformat<
    localized_unit_group,
    minimal_injective_ideals,
    minimal_results              // ReductionFormat, parallel to the ideals
>;

ClassificationFormat := recformat<
    localized_groups,
    exclusion_reasons,           // "" unless T is excluded as trivial
    poset_results                // false for excluded T
>;

// Data shared by the computations for one order. The last two fields cache
// FiniteQuotient for each p^k and LocalImage for each (T, p^k).
ContextFormat := recformat<
    order_data,
    normalizer_lookup,           // projective_key of a quaternion -> element of N(O)/K^*
    quotients,
    images
>;


// A string that two quaternions share exactly when they differ by a nonzero scalar.
function projective_key(order_data, x)
    return Sprint(Eltseq(ProjectiveRepresentative(order_data`quaternion_algebra, x)));
end function;


function subset_key(T)
    return Sprint(Sort([CanonicalIdealKey(p) : p in T]));
end function;


// Ramified primes at which O is locally maximal. Only these may lie in T,
// because alpha_p needs local maximality.
function admissible_ramified_primes(order_data)
    return [p : p in RamifiedPrimes(order_data) | is_locally_maximal(order_data, p)];
end function;


function classification_context(order_data)
    lookup := AssociativeArray();
    for g in order_data`normalizer_group do
        lookup[projective_key(order_data, order_data`normalizer_map(g))] := g;
    end for;
    return rec<ContextFormat |
        order_data := order_data,
        normalizer_lookup := lookup,
        quotients := AssociativeArray(),
        images := AssociativeArray()
    >;
end function;


// The primitive quaternion representing an element of N(O)/K^*.
function NormalizerRepresentative(order_data, g)
    return PrimitiveRepresentative(order_data, order_data`normalizer_map(g));
end function;


// ---------------------------------------------------------------------------
// The groups Gamma_T
// ---------------------------------------------------------------------------

// Gamma_T, generated by the units of O and alpha_p for each p in T.
function localized_group(context, T)
    order_data := context`order_data;
    admissible := admissible_ramified_primes(order_data);
    R := order_data`integer_ring;
    T := SortIdeals([ideal<R | Generators(p)> : p in T]);
    if exists{p : p in T | p notin admissible} then
        error "T may only contain ramified primes at which O is maximal.";
    end if;
    if #T gt 0 and order_data`order_type lt 2 then
        error "Nonempty T needs an Eichler order.";
    end if;

    elements := [PrimitiveRepresentative(order_data, order_data`unit_map(order_data`unit_group.i))
                 : i in [1..Ngens(order_data`unit_group)]]
                cat [TwoSidedGenerator(order_data, p) : p in T];
    N := order_data`normalizer_group;
    subgroup := sub<N | [context`normalizer_lookup[projective_key(order_data, x)] : x in elements]
                        cat [Identity(N)]>;
    if #T eq 0 then
        assert #subgroup eq #order_data`unit_group;
    end if;

    return rec<LocalizedGroupFormat |
        order_data := order_data,
        admissible_ramified_primes := admissible,
        ramified_subset := T,
        subgroup := subgroup,
        subgroup_order := #subgroup,
        generator_elements := elements
    >;
end function;


// The context and Gamma_T for every admissible T, Gamma_emptyset first.
function context_with_all_groups(order_data)
    context := classification_context(order_data);
    primes := admissible_ramified_primes(order_data);
    groups := [localized_group(context, [primes[i] : i in [1..#primes] | IsOdd(mask div 2^(i - 1))])
               : mask in [0..2^#primes - 1]];
    return context, groups;
end function;


function LocalizedGroups(order_data)
    _, groups := context_with_all_groups(order_data);
    return groups;
end function;


// ---------------------------------------------------------------------------
// Reduction of Gamma_T
// ---------------------------------------------------------------------------

// An element of N(O) whose reduced norm has odd valuation at p is not in
// G_{p^k}, so if Gamma_T has one, Gamma_T reduces into W_{p^k} instead.
procedure LocalImage(~context, group, p, k, ~local_image)
    key := Sprintf("%o %o^%o", subset_key(group`ramified_subset), CanonicalIdealKey(p), k);
    if IsDefined(context`images, key) then
        local_image := context`images[key];
        return;
    end if;

    quotient_key := Sprintf("%o^%o", CanonicalIdealKey(p), k);
    if not IsDefined(context`quotients, quotient_key) then
        context`quotients[quotient_key] := FiniteQuotient(context`order_data, p, k);
    end if;
    Q := context`quotients[quotient_key];

    R := context`order_data`integer_ring;
    uses_extension := exists{x : x in group`generator_elements | IsOdd(Valuation(Norm(x) * R, p))};
    if uses_extension then
        if Q`extension cmpeq false then
            error "The extension W is not available for a prime in T.";
        end if;
        ambient := Q`extension;
        images := [NormalizerImage(Q, x) : x in group`generator_elements];
    else
        ambient := Q`group;
        images := [QuotientImage(Q, x) : x in group`generator_elements];
    end if;

    local_image := rec<LocalImageFormat |
        quotient := Q,
        uses_extension := uses_extension,
        ambient_group := ambient,
        image_subgroup := sub<ambient | images cat [Identity(ambient)]>,
        generator_images := images
    >;
    context`images[key] := local_image;
end procedure;


// One subgroup from each conjugacy class of complements of K in G. Subgroups
// runs on an isomorphic copy of smaller degree.
function ComplementClasses(G, K)
    if #G mod #K ne 0 then
        return [];
    end if;
    if #K eq 1 then
        return [G];
    end if;
    small, f := DegreeReduction(G);
    K_small := f(K);
    return [c`subgroup @@ f : c in Subgroups(small : OrderEqual := #G div #K)
            | #(c`subgroup meet K_small) eq 1];
end function;


procedure add_complements(~result)
    result`complement_classes := ComplementClasses(result`ambient_group, result`image_subgroup);
    result`normal_complement_classes :=
        [H : H in result`complement_classes | IsNormal(result`ambient_group, H)];
end procedure;


// By the Chinese remainder theorem, G_C is the direct product of the groups at
// the prime powers of C, and Gamma_T maps into it diagonally. The reduction is
// injective when the image has order |Gamma_T|. Complements are not computed.
procedure reduction(~context, group, C, ~result)
    factors := [];
    for factor in Factorization(C) do
        local_image := false;
        LocalImage(~context, group, factor[1], factor[2], ~local_image);
        Append(~factors, local_image);
    end for;

    if #factors eq 1 then
        ambient := factors[1]`ambient_group;
        embeddings := [IdentityHomomorphism(ambient)];
    else
        ambient, embeddings := DirectProduct([f`ambient_group : f in factors]);
    end if;
    images := [&*[embeddings[i](factors[i]`generator_images[j]) : i in [1..#factors]]
               : j in [1..#group`generator_elements]];
    image := sub<ambient | images cat [Identity(ambient)]>;
    assert group`subgroup_order mod #image eq 0;

    result := rec<ReductionFormat |
        localized_unit_group := group,
        modulus_ideal := C,
        factors := factors,
        embeddings := embeddings,
        ambient_group := ambient,
        image_subgroup := image,
        injective := #image eq group`subgroup_order
    >;
end procedure;


// The image in G_C of an element of O, given as a primitive quaternion x.
function ReductionImage(result, x)
    image := Identity(result`ambient_group);
    for i in [1..#result`factors] do
        factor := result`factors[i];
        local_image := factor`uses_extension
            select NormalizerImage(factor`quotient, x)
            else QuotientImage(factor`quotient, x);
        image *:= result`embeddings[i](local_image);
    end for;
    return image;
end function;


// Gamma_T -> G_C and all complement classes for one modulus C.
function ReductionData(order_data, T, C)
    context := classification_context(order_data);
    result := false;
    reduction(~context, localized_group(context, T), ideal<order_data`integer_ring | Generators(C)>, ~result);
    add_complements(~result);
    return result;
end function;


// ---------------------------------------------------------------------------
// Minimal injective ideals
// ---------------------------------------------------------------------------

// Breadth-first search over exponent vectors on the ramified primes and the split
// primes of norm at most |Gamma_T|. Vectors are visited in order of total degree,
// so every minimal injective vector is reached before its multiples. Reduction
// stays injective at multiples, so the search does not go above an injective
// vector; it ends because reduction modulo a high enough power is injective.
// Complements are computed only at the minimal ideals.
procedure minimal_ideals(~context, group, ~poset)
    primes := RelevantPrimes(context`order_data, group`subgroup_order);
    frontier := [[i eq j select 1 else 0 : j in [1..#primes]] : i in [1..#primes]];
    tested := AssociativeArray();
    minimal_vectors := [];
    ideals := [];
    results := [];
    divides := func<u, v | forall{i : i in [1..#u] | u[i] le v[i]}>;

    while #frontier gt 0 do
        vector := frontier[1];
        Remove(~frontier, 1);
        if IsDefined(tested, vector) or exists{m : m in minimal_vectors | divides(m, vector)} then
            continue;
        end if;
        tested[vector] := true;

        C := &*[primes[i]^vector[i] : i in [1..#primes] | vector[i] gt 0];
        result := false;
        reduction(~context, group, C, ~result);
        if result`injective then
            add_complements(~result);
            Append(~minimal_vectors, vector);
            Append(~ideals, C);
            Append(~results, result);
            continue;
        end if;
        for i in [1..#primes] do
            successor := vector;
            successor[i] +:= 1;
            if successor notin frontier then
                Append(~frontier, successor);
            end if;
        end for;
    end while;

    poset := rec<PosetFormat |
        localized_unit_group := group,
        minimal_injective_ideals := ideals,
        minimal_results := results
    >;
end procedure;


// The minimal ideals C with pi_C injective on Gamma_T, with their reductions and complements.
function MinimalComplementaryIdeals(order_data, T)
    context := classification_context(order_data);
    poset := false;
    minimal_ideals(~context, localized_group(context, T), ~poset);
    return poset;
end function;


// ---------------------------------------------------------------------------
// Nontriviality and the classification of one order
// ---------------------------------------------------------------------------

// The two trivial cases excluded by the paper's definition of a nontrivial
// minimal complementary triple, or "".
function ClassificationExclusionReason(gamma_emptyset, group)
    if gamma_emptyset`subgroup_order ne 1 then
        return "";
    elif #group`ramified_subset eq 0 then
        return "Gamma_emptyset=1 and T=emptyset";
    elif #group`ramified_subset eq 1 and #group`admissible_ramified_primes eq 1 then
        return "Gamma_emptyset=1, #T=1, and no distinct ramified modulus prime";
    end if;
    return "";
end function;


// For trivial Gamma_emptyset and T = {p}, C must involve a ramified prime other than p.
function IsNontrivialMinimalIdeal(gamma_emptyset, group, C)
    if gamma_emptyset`subgroup_order ne 1 or #group`ramified_subset gt 1 then
        return true;
    elif #group`ramified_subset eq 0 then
        return false;
    end if;
    return exists{f : f in Factorization(C) | f[1] ne group`ramified_subset[1] and
                                              f[1] in group`admissible_ramified_primes};
end function;


// Every Gamma_T of the order, with the nontrivial minimal ideals and their complements.
function ClassifyOrder(order_data)
    context, groups := context_with_all_groups(order_data);
    gamma_emptyset := groups[1];
    reasons := [ClassificationExclusionReason(gamma_emptyset, group) : group in groups];
    posets := [* *];
    for i in [1..#groups] do
        if reasons[i] ne "" then
            Append(~posets, false);
            continue;
        end if;
        poset := false;
        minimal_ideals(~context, groups[i], ~poset);
        keep := [j : j in [1..#poset`minimal_injective_ideals] |
                 IsNontrivialMinimalIdeal(gamma_emptyset, groups[i], poset`minimal_injective_ideals[j])];
        poset`minimal_injective_ideals := poset`minimal_injective_ideals[keep];
        poset`minimal_results := poset`minimal_results[keep];
        Append(~posets, poset);
    end for;
    return rec<ClassificationFormat |
        localized_groups := groups,
        exclusion_reasons := reasons,
        poset_results := posets
    >;
end function;

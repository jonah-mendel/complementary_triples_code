// ============================================================================
// Order-data construction for the complementary-triples computation package.
//
// Main API:
// - order_data_from_index(idx)
// - build_order_data_for_order(idx, base_field, quaternion_algebra, quaternion_order :
//       label := "main", order_type := 4, class_number := 0)
// - maximal_orders_up_to_conjugacy(base_field, quaternion_algebra)
// - build_maximal_orders(base_field, quaternion_algebra)
//
// Scope:
// - only class-number-one base fields are supported;
// - OneClassGenera rows follow the format documented at
//   https://www.math.uni-bielefeld.de/~mkirschm/orders/
// ============================================================================
// Record storing the arithmetic data attached to one quaternion order.
order_data_format := recformat<
    index,
    label,
    base_field,
    integer_ring,
    quaternion_algebra,
    quaternion_order,
    order_discriminant,
    order_type,
    class_number,
    principal_basis,
    unit_group,
    unit_elements,
    unit_map,
    normalizer_group,
    normalizer_elements,
    normalizer_map
>;


// The generic maximal-order path assumes the base field has class number one.
procedure validate_class_number_one_integer_ring(integer_ring)
    if ClassNumber(integer_ring) ne 1 then
        error "The base field must have class number one.";
    end if;
end procedure;


// Return the OneClassGenera entry attached to the given positive index.
function one_class_genera_entry(idx)
    if Type(idx) ne RngIntElt or idx lt 1 then
        error "idx must be a positive integer.";
    end if;

    if idx gt #OneClassGenera then
        error "idx is outside the OneClassGenera table.";
    end if;

    return OneClassGenera[idx];
end function;


// Convert one table entry into its ambient arithmetic data.
function algebra_data_from_entry(entry)
    polynomial_f := Polynomial(entry[1]);
    base_field := (Degree(polynomial_f) eq 1) select RationalsAsNumberField() else NumberField(polynomial_f);
    integer_ring := RingOfIntegers(base_field);

    quaternion_algebra<i, j> := QuaternionAlgebra< base_field | entry[3], entry[4] >;
    order_basis := ChangeUniverse(entry[5], quaternion_algebra);
    quaternion_order := Order(order_basis);

    return base_field, integer_ring, quaternion_algebra, quaternion_order;
end function;


// Return the class number of the given quaternion order.
function order_class_number(quaternion_order)
    return #RightIdealClasses(quaternion_order);
end function;


// Extract a principal basis for the order.
function find_principal_basis_for_order(quaternion_order)
    if Type(BaseRing(quaternion_order)) eq RngInt then
        return Basis(quaternion_order);
    end if;

    pseudo_basis := PseudoBasis(quaternion_order);
    principal_basis := [quaternion_order!1, quaternion_order!1, quaternion_order!1, quaternion_order!1];

    for i in [1..4] do
        is_principal, generator := IsPrincipal(pseudo_basis[i][1]);
        if not is_principal then
            error "Pseudo-basis entry is not principal at index", i;
        end if;

        principal_basis[i] := pseudo_basis[i][2] * generator;
    end for;

    return principal_basis;
end function;


// Normalize a quaternion element so its first nonzero ambient coefficient is 1.
function normalize_quaternion_element(quaternion_algebra, element_x)
    coefficients := Eltseq(quaternion_algebra!element_x);

    for coefficient in coefficients do
        if coefficient ne 0 then
            return quaternion_algebra![c / coefficient : c in coefficients];
        end if;
    end for;

    error "Cannot normalize the zero quaternion element.";
end function;


// Express an element in the chosen principal basis of the order.
function order_coordinates_in_basis(base_field, quaternion_algebra, basis, element_x)
    basis_matrix := Matrix(base_field, 4, 4, &cat([Eltseq(quaternion_algebra!b) : b in basis]));
    x_vector := Vector(base_field, [base_field!c : c in Eltseq(quaternion_algebra!element_x)]);
    is_consistent, solution := IsConsistent(basis_matrix, x_vector);

    if not is_consistent then
        error "Element is not expressible in the chosen basis.";
    end if;

    return Eltseq(solution);
end function;


// Rebuild an order element in the ambient algebra from principal-basis coordinates.
function quaternion_from_principal_basis(quaternion_algebra, principal_basis, coordinates)
    return quaternion_algebra!&+[coordinates[i] * principal_basis[i] : i in [1..4]];
end function;


// Return a primitive scalar a / b for the fractional ideal generated by coordinates.
function primitive_scaling_from_coordinates(integer_ring, coordinates)
    coordinate_ideal := ideal<integer_ring | coordinates>;
    denominator_ideal := ideal<integer_ring | 1>;
    numerator_ideal := ideal<integer_ring | 1>;

    for factor in Factorization(coordinate_ideal) do
        if factor[2] lt 0 then
            denominator_ideal *:= factor[1]^(-factor[2]);
        elif factor[2] gt 0 then
            numerator_ideal *:= factor[1]^(factor[2]);
        end if;
    end for;

    is_principal, denominator_generator := IsPrincipal(denominator_ideal);
    if not is_principal then
        error "The denominator ideal for a normalizer representative is not principal.";
    end if;

    is_principal, numerator_generator := IsPrincipal(numerator_ideal);

    if not is_principal then
        error "The numerator ideal for a normalizer representative is not principal.";
    end if;

    return denominator_generator / numerator_generator;
end function;


// Replace a normalizer class representative by a primitive integral element of the order.
function integral_normalizer_representative(
    base_field,
    integer_ring,
    quaternion_algebra,
    quaternion_order,
    principal_basis,
    element_x
)
    coordinates := order_coordinates_in_basis(base_field, quaternion_algebra, principal_basis, element_x);
    scaling_element := primitive_scaling_from_coordinates(integer_ring, coordinates);

    integral_coordinates := [];

    for coefficient in coordinates do
        scaled_coefficient := scaling_element * coefficient;
        if not (scaled_coefficient in integer_ring) then
            error "Failed to clear denominators for a normalizer representative.";
        end if;

        Append(~integral_coordinates, integer_ring!scaled_coefficient);
    end for;

    return quaternion_from_principal_basis(quaternion_algebra, principal_basis, integral_coordinates);
end function;


// Check that every normalized unit representative also occurs among the
// normalized normalizer representatives.
procedure validate_unit_subset_of_normalizer(quaternion_algebra, unit_elements, normalizer_elements)
    normalizer_lookup := AssociativeArray();

    for normalizer_element in normalizer_elements do
        normalized_normalizer := normalize_quaternion_element(quaternion_algebra, normalizer_element);
        normalizer_lookup[Sprint(Eltseq(normalized_normalizer))] := true;
    end for;

    for unit_element in unit_elements do
        normalized_unit := normalize_quaternion_element(quaternion_algebra, unit_element);
        if not IsDefined(normalizer_lookup, Sprint(Eltseq(normalized_unit))) then
            error "A normalized unit representative was not found among the normalized normalizer representatives.";
        end if;
    end for;
end procedure;


// Replace a normalizer representative by the exact stored unit when the two
// define the same normalized quaternion class.
function align_normalizer_representatives_with_units(quaternion_algebra, unit_elements, normalizer_elements)
    normalized_unit_lookup := AssociativeArray();
    aligned_normalizers := [];

    for unit_element in unit_elements do
        normalized_unit := normalize_quaternion_element(quaternion_algebra, unit_element);
        normalized_unit_lookup[Sprint(Eltseq(normalized_unit))] := unit_element;
    end for;

    for normalizer_element in normalizer_elements do
        normalized_normalizer := normalize_quaternion_element(quaternion_algebra, normalizer_element);
        normalized_key := Sprint(Eltseq(normalized_normalizer));

        if IsDefined(normalized_unit_lookup, normalized_key) then
            Append(~aligned_normalizers, normalized_unit_lookup[normalized_key]);
        else
            Append(~aligned_normalizers, normalizer_element);
        end if;
    end for;

    return aligned_normalizers;
end function;


// Collect unit representatives in O and integral normalizer representatives in O.
function group_data_for_order(base_field, integer_ring, quaternion_algebra, quaternion_order, principal_basis)
    unit_group, unit_map := UnitGroup(quaternion_order);
    unit_elements := [];
    for unit_u in unit_group do
        unit_coordinates := order_coordinates_in_basis(
            base_field,
            quaternion_algebra,
            principal_basis,
            unit_map(unit_u)
        );

        for coefficient in unit_coordinates do
            if not (coefficient in integer_ring) then
                error "A unit representative has non-integral principal-basis coordinates.";
            end if;
        end for;

        Append(
            ~unit_elements,
            quaternion_from_principal_basis(quaternion_algebra, principal_basis, [integer_ring!c : c in unit_coordinates])
        );
    end for;

    normalizer_group, normalizer_map := Normalizer(quaternion_order);
    normalizer_elements := [
        integral_normalizer_representative(
            base_field,
            integer_ring,
            quaternion_algebra,
            quaternion_order,
            principal_basis,
            normalizer_map(g)
        ) : g in normalizer_group
    ];
    normalizer_elements := align_normalizer_representatives_with_units(
        quaternion_algebra,
        unit_elements,
        normalizer_elements
    );

    validate_unit_subset_of_normalizer(quaternion_algebra, unit_elements, normalizer_elements);

    return unit_group, unit_elements, unit_map,
           normalizer_group, normalizer_elements, normalizer_map;
end function;


// Build one order record.
function build_order_data(
    idx,
    base_field,
    integer_ring,
    quaternion_algebra,
    quaternion_order,
    order_type,
    class_number :
    label := "main"
)
    principal_basis := find_principal_basis_for_order(quaternion_order);
    unit_group, unit_elements, unit_map,
    normalizer_group, normalizer_elements, normalizer_map :=
        group_data_for_order(base_field, integer_ring, quaternion_algebra, quaternion_order, principal_basis);

    return rec<order_data_format |
        index := idx,
        label := label,
        base_field := base_field,
        integer_ring := integer_ring,
        quaternion_algebra := quaternion_algebra,
        quaternion_order := quaternion_order,
        order_discriminant := Discriminant(quaternion_order),
        order_type := order_type,
        class_number := class_number,
        principal_basis := principal_basis,
        unit_group := unit_group,
        unit_elements := unit_elements,
        unit_map := unit_map,
        normalizer_group := normalizer_group,
        normalizer_elements := normalizer_elements,
        normalizer_map := normalizer_map
    >;
end function;


// Build order data for one explicit quaternion order over a class-number-one
// number field.
function build_order_data_for_order(
    idx,
    base_field,
    quaternion_algebra,
    quaternion_order :
    label := "main",
    order_type := 4,
    class_number := 0
)
    if Type(base_field) ne FldNum and Type(base_field) ne FldRat then
        error "base_field must be a number field or the rational field.";
    end if;

    integer_ring := RingOfIntegers(base_field);
    validate_class_number_one_integer_ring(integer_ring);

    if class_number eq 0 then
        class_number := order_class_number(quaternion_order);
    end if;

    return build_order_data(
        idx,
        base_field,
        integer_ring,
        quaternion_algebra,
        quaternion_order,
        order_type,
        class_number :
        label := label
    );
end function;


// Enumerate representatives of the maximal orders up to conjugacy.
function maximal_orders_up_to_conjugacy(base_field, quaternion_algebra)
    if Type(base_field) ne FldNum and Type(base_field) ne FldRat then
        error "base_field must be a number field or the rational field.";
    end if;

    validate_class_number_one_integer_ring(RingOfIntegers(base_field));

    representative_order := MaximalOrder(quaternion_algebra);
    maximal_orders := [];

    for right_ideal in RightIdealClasses(representative_order) do
        candidate_order := LeftOrder(right_ideal);
        is_new := true;

        for existing_order in maximal_orders do
            if IsConjugate(candidate_order, existing_order) then
                is_new := false;
                break;
            end if;
        end for;

        if is_new then
            Append(~maximal_orders, candidate_order);
        end if;
    end for;

    return maximal_orders;
end function;


// Build order data for each maximal-order conjugacy class of the algebra.
function build_maximal_orders(base_field, quaternion_algebra)
    maximal_orders := maximal_orders_up_to_conjugacy(base_field, quaternion_algebra);
    maximal_order_data := [];

    for order_number in [1..#maximal_orders] do
        Append(
            ~maximal_order_data,
            build_order_data_for_order(
                0,
                base_field,
                quaternion_algebra,
                maximal_orders[order_number] :
                label := Sprintf("maximal_%o", order_number),
                order_type := 4
            )
        );
    end for;

    return maximal_order_data;
end function;


// Read the arithmetic data attached to OneClassGenera[idx].
function base_order_data_from_index(idx)
    entry := one_class_genera_entry(idx);
    base_field, integer_ring, quaternion_algebra, quaternion_order := algebra_data_from_entry(entry);
    return entry, base_field, integer_ring, quaternion_algebra, quaternion_order;
end function;


// Build the main order attached to OneClassGenera[idx].
function order_data_from_index(idx)
    entry, base_field, integer_ring, quaternion_algebra, quaternion_order := base_order_data_from_index(idx);
    validate_class_number_one_integer_ring(integer_ring);

    order_type := entry[6];
    class_number := entry[7];

    return build_order_data(
        idx,
        base_field,
        integer_ring,
        quaternion_algebra,
        quaternion_order,
        order_type,
        class_number :
        label := "main"
    );
end function;
